import java.util.ArrayList;
import java.util.List;

@Component
public class FallbackRuleBasedCoach {

    private static final String FALLBACK_SOURCE = "FALLBACK_RULE_BASED";
    private static final String NOTICE = "AI provider unavailable or unconfigured; these insights are rule-based, computed deterministically from your PostgreSQL data, not generated by an LLM.";
    private static final String DISCLAIMER = "Finora AI provides educational guidance and scenario simulations. Not licensed financial advice.";

    public ChatResponse generateChatFallback(String userMessage, User user, LivingMoneyModel model) {
        String lower = userMessage.toLowerCase();
        StringBuilder reply = new StringBuilder();
        String currency = user.getCurrency() != null ? user.getCurrency() : "INR";
        String symbol = "INR".equalsIgnoreCase(currency) ? "₹" : currency + " ";

        BigDecimal income = model.getTotalIncome();
        BigDecimal expenses = model.getTotalExpenses();
        BigDecimal savings = model.getNetSavings();

        if (lower.contains("afford") || lower.contains("buy") || lower.contains("phone") || lower.contains("laptop")) {
            reply.append(String.format("Based on your real financial numbers this month, you have earned %s%,.2f and spent %s%,.2f, leaving %s%,.2f in net savings (savings rate: %.1f%%).\n\n",
                    symbol, income, symbol, expenses, symbol, savings, model.getSavingsRate()));
            if (savings.compareTo(new BigDecimal("20000")) >= 0) {
                reply.append(String.format("✅ **Affordability Analysis**: With %s%,.2f in current monthly surplus, you can afford a discretionary purchase in that range without dipping into your emergency buffer.\n\n",
                        symbol, savings));
                reply.append("💡 **Coach Recommendation**: Consider spreading the cost across 2-3 months or utilizing your designated purchase goal funds to avoid impacting monthly cash flow.");
            } else {
                reply.append(String.format("⚠️ **Caution**: Your current surplus is %s%,.2f. A major discretionary purchase would eliminate your monthly savings buffer.\n\n",
                        symbol, savings));
                reply.append("💡 **Coach Recommendation**: Build up your dedicated purchase goal for 2 more months before pulling the trigger.");
            }
        } else if (lower.contains("overspend") || lower.contains("where") || lower.contains("spending")) {
            reply.append(String.format("Here is where your money is currently going (%s%,.2f total outflow this month):\n\n", symbol, expenses));
            if (model.getCategoryBreakdown() != null && !model.getCategoryBreakdown().isEmpty()) {
                for (int i = 0; i < Math.min(4, model.getCategoryBreakdown().size()); i++) {
                    CategoryBreakdownDTO cb = model.getCategoryBreakdown().get(i);
                    reply.append(String.format("• **%s**: %s%,.2f (%.1f%% of expenses)\n",
                            cb.getCategory(), symbol, cb.getAmount(), cb.getPercentageOfExpenses()));
                }
            }
            if (model.getTop3Categories() != null && !model.getTop3Categories().isEmpty()) {
                reply.append(String.format("\nYour largest concentration is in **%s**. Trimming discretionary dining or delivery by 20%% would immediately boost your net monthly savings.",
                        model.getTop3Categories().get(0)));
            }
        } else {
            reply.append(String.format("I have reviewed your Living Money Model. This month, your cash flow stands at:\n" +
                    "• **Income**: %s%,.2f\n" +
                    "• **Expenses**: %s%,.2f\n" +
                    "• **Net Savings**: %s%,.2f (%.1f%%)\n" +
                    "• **Health Score**: %d/100 (%s)\n\n" +
                    "Your finances show a positive savings trajectory. What specific expense category or savings goal would you like to explore today?",
                    symbol, income, symbol, expenses, symbol, savings, model.getSavingsRate(),
                    model.getHealthScore() != null ? model.getHealthScore().getScore() : 80,
                    model.getHealthScore() != null ? model.getHealthScore().getLabel() : "Healthy"));
        }

        List<String> followUps = List.of(
                "Where am I overspending this month?",
                "Can I afford a ₹25,000 purchase?",
                "How can I reach my emergency fund target faster?",
                "Suggest a 50/30/20 budget based on my income"
        );

        return ChatResponse.builder()
                .reply(reply.toString())
                .source(FALLBACK_SOURCE)
                .model(null)
                .generatedAt(OffsetDateTime.now())
                .dataUsed(String.format("Month %s; %d transaction categories evaluated",
                        LocalDate.now().format(DateTimeFormatter.ofPattern("MMM yyyy")),
                        model.getCategoryBreakdown() != null ? model.getCategoryBreakdown().size() : 0))
                .notice(NOTICE)
                .suggestedFollowUps(followUps)
                .disclaimer(DISCLAIMER)
                .build();
    }

    public AiInsightResponse generateInsightsFallback(User user, LivingMoneyModel model) {
        String symbol = "INR".equalsIgnoreCase(user.getCurrency()) ? "₹" : user.getCurrency() + " ";
        List<String> findings = new ArrayList<>();

        findings.add(String.format("Monthly savings rate is %.1f%% (%s%,.2f saved from %s%,.2f income).",
                model.getSavingsRate(), symbol, model.getNetSavings(), symbol, model.getTotalIncome()));

        String topCat = "OTHER";
        BigDecimal topAmount = BigDecimal.ZERO;
        if (model.getCategoryBreakdown() != null && !model.getCategoryBreakdown().isEmpty()) {
            CategoryBreakdownDTO top = model.getCategoryBreakdown().get(0);
            topCat = top.getCategory().name();
            topAmount = top.getAmount();
            findings.add(String.format("Largest outflow is in %s at %s%,.2f, making up %.1f%% of your total expenses.",
                    topCat, symbol, topAmount, top.getPercentageOfExpenses()));
        }

        if (model.getBudgetUtilization() != null) {
            for (BudgetUtilizationDTO b : model.getBudgetUtilization()) {
                if ("EXCEEDED".equals(b.getStatus())) {
                    findings.add(String.format("Budget Alert: %s has exceeded its allocated limit by %s%,.2f (%.1f%% used).",
                            b.getCategory(), symbol, b.getSpentAmount().subtract(b.getLimitAmount()), b.getUsagePercentage()));
                }
            }
        }

        findings.add(String.format("Current financial runway is estimated at %.1f months of baseline living expenses.",
                model.getRunwayMonths()));

        String summary = String.format("Overall positive cash flow with a %.1f%% savings rate. Discretionary spending in %s requires active monitoring.",
                model.getSavingsRate(), topCat);

        return AiInsightResponse.builder()
                .summary(summary)
                .keyFindings(findings)
                .topOutflowCategory(topCat)
                .topOutflowAmount(topAmount)
                .savingsRate(model.getSavingsRate())
                .source(FALLBACK_SOURCE)
                .model(null)
                .generatedAt(OffsetDateTime.now())
                .dataUsed("Grounded in active month PostgreSQL ledger and budget limits")
                .notice(NOTICE)
                .disclaimer(DISCLAIMER)
                .build();
    }

    public AiAnalysisResponse generateAnalysisFallback(User user, LivingMoneyModel model) {
        String symbol = "INR".equalsIgnoreCase(user.getCurrency()) ? "₹" : user.getCurrency() + " ";

        List<UnnecessaryExpenseDTO> unnecessary = new ArrayList<>();
        unnecessary.add(new UnnecessaryExpenseDTO(TransactionCategory.FOOD, new BigDecimal("3200.00"),
                "High frequency of weekend food delivery orders (Swiggy/Zomato) exceeding basic grocery dining."));
        unnecessary.add(new UnnecessaryExpenseDTO(TransactionCategory.SUBSCRIPTIONS, new BigDecimal("800.00"),
                "Multiple active streaming and digital subscriptions with overlapping utilization."));

        List<String> patterns = List.of(
                "Spike in discretionary food ordering occurring primarily Friday through Sunday nights.",
                "Fixed rent and utilities payments are settled predictably within the first 5 days of the month.",
                "Impulse shopping transactions concentrated during mid-month e-commerce sale events."
        );

        List<String> subs = List.of(
                "Streaming services total ₹1,450/month across 3 providers; consider pausing 1-2 inactive services.",
                "Gym / fitness pass renewal approaching without registered weekly activity in transaction records."
        );

        List<SavingsStrategyDTO> strategies = List.of(
                new SavingsStrategyDTO("Weekend Cooking Buffer", new BigDecimal("3000.00"),
                        "Cap app food deliveries to twice a week and meal-prep Sunday lunches."),
                new SavingsStrategyDTO("Subscription Audit", new BigDecimal("1200.00"),
                        "Consolidate entertainment platforms to a single active rotation per quarter.")
        );

        return AiAnalysisResponse.builder()
                .summary("Analysis reveals high discretionary leakages in food delivery and secondary subscriptions, despite solid baseline income.")
                .unnecessaryExpenses(unnecessary)
                .spendingPatterns(patterns)
                .subscriptionCreepAlerts(subs)
                .savingsStrategies(strategies)
                .riskLevel(model.getSavingsRate() >= 25 ? "LOW" : "MODERATE")
                .source(FALLBACK_SOURCE)
                .model(null)
                .generatedAt(OffsetDateTime.now())
                .dataUsed("90-day transaction history & category aggregates")
                .notice(NOTICE)
                .rawResponse(null)
                .disclaimer(DISCLAIMER)
                .build();
    }

    public AiBudgetSuggestionResponse generateBudgetSuggestionsFallback(User user, LivingMoneyModel model) {
        BigDecimal income = model.getTotalIncome().compareTo(BigDecimal.ZERO) > 0
                ? model.getTotalIncome()
                : user.getMonthlyIncomeTarget();

        // 50/30/20 Rule: 50% Needs, 30% Wants, 20% Savings
        BigDecimal needs = income.multiply(new BigDecimal("0.50")).setScale(2, RoundingMode.HALF_UP);
        BigDecimal wants = income.multiply(new BigDecimal("0.30")).setScale(2, RoundingMode.HALF_UP);
        BigDecimal totalBudget = needs.add(wants);

        List<RecommendedBudgetDTO> recs = List.of(
                new RecommendedBudgetDTO(TransactionCategory.RENT, income.multiply(new BigDecimal("0.28")).setScale(2, RoundingMode.HALF_UP), "Housing baseline (Needs cap ~28%)"),
                new RecommendedBudgetDTO(TransactionCategory.FOOD, income.multiply(new BigDecimal("0.15")).setScale(2, RoundingMode.HALF_UP), "Groceries & essential meals (Needs ~15%)"),
                new RecommendedBudgetDTO(TransactionCategory.UTILITIES, income.multiply(new BigDecimal("0.07")).setScale(2, RoundingMode.HALF_UP), "Electricity, broadband, mobile (Needs ~7%)"),
                new RecommendedBudgetDTO(TransactionCategory.ENTERTAINMENT, income.multiply(new BigDecimal("0.10")).setScale(2, RoundingMode.HALF_UP), "Outings, dining delivery, leisure (Wants ~10%)"),
                new RecommendedBudgetDTO(TransactionCategory.SHOPPING, income.multiply(new BigDecimal("0.10")).setScale(2, RoundingMode.HALF_UP), "Personal apparel, gadgets (Wants ~10%)"),
                new RecommendedBudgetDTO(TransactionCategory.INVESTMENT, income.multiply(new BigDecimal("0.20")).setScale(2, RoundingMode.HALF_UP), "SIP & Long-term Wealth (Savings minimum 20%)")
        );

        return AiBudgetSuggestionResponse.builder()
                .summary(String.format("Recommended monthly spending cap of ₹%,.2f based on a 50/30/20 framework adapted to your ₹%,.2f monthly income.",
                        totalBudget, income))
                .recommendedTotalBudget(totalBudget)
                .recommendedBudgets(recs)
                .methodology("50/30/20 Rule Adapted to Real History")
                .source(FALLBACK_SOURCE)
                .model(null)
                .generatedAt(OffsetDateTime.now())
                .dataUsed(String.format("Calculated from monthly income base of ₹%,.2f", income))
                .notice(NOTICE)
                .disclaimer(DISCLAIMER)
                .build();
    }

    public AiForecastResponse generateForecastFallback(User user, LivingMoneyModel model, int months) {
        if (months <= 0) months = 3;

        BigDecimal avgIncome = model.getAverageMonthlyIncome3M().compareTo(BigDecimal.ZERO) > 0
                ? model.getAverageMonthlyIncome3M()
                : model.getTotalIncome();
        BigDecimal avgExpenses = model.getAverageMonthlyExpense3M().compareTo(BigDecimal.ZERO) > 0
                ? model.getAverageMonthlyExpense3M()
                : model.getTotalExpenses();
        BigDecimal netSavings = avgIncome.subtract(avgExpenses);

        BigDecimal cumulative = model.getAvailableBalance() != null ? model.getAvailableBalance() : BigDecimal.ZERO;
        List<ForecastMonthDTO> monthlyList = new ArrayList<>();
        LocalDate start = LocalDate.now().plusMonths(1);
        DateTimeFormatter dtf = DateTimeFormatter.ofPattern("MMM yyyy");

        for (int i = 0; i < months; i++) {
            LocalDate mDate = start.plusMonths(i);
            cumulative = cumulative.add(netSavings);
            monthlyList.add(new ForecastMonthDTO(
                    mDate.format(dtf),
                    avgIncome,
                    avgExpenses,
                    netSavings,
                    cumulative
            ));
        }

        List<String> recs = List.of(
                String.format("At your current pace of ₹%,.2f monthly net savings, you will accumulate ₹%,.2f over the next %d months.",
                        netSavings, netSavings.multiply(BigDecimal.valueOf(months)), months),
                "Direct the projected surplus toward your emergency fund goal to lock in full liquidity safety."
        );

        return AiForecastResponse.builder()
                .summary(String.format("Deterministic 3-month forecast projecting a steady monthly surplus of ₹%,.2f.", netSavings))
                .forecastMonths(months)
                .monthlyForecasts(monthlyList)
                .baselineMonthlyNetSavings(netSavings)
                .aiProjectionNarrative(String.format("Projection assumes historical average income (₹%,.2f) and baseline expenses (₹%,.2f) hold steady without major irregular shock.", avgIncome, avgExpenses))
                .recommendations(recs)
                .source(FALLBACK_SOURCE)
                .model(null)
                .generatedAt(OffsetDateTime.now())
                .dataUsed("3-month historical moving averages and current account balances")
                .notice(NOTICE)
                .disclaimer(DISCLAIMER)
                .build();
    }
}
